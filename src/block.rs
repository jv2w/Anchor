/// A block state property: its name and value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Property {
    name: &'static str,
    value: PropertyValue<'static>,
}

impl Property {
    /// The property name, such as `facing_direction`.
    pub fn name(&self) -> &'static str {
        self.name
    }

    /// The property value.
    #[inline]
    pub fn value(&self) -> PropertyValue<'static> {
        self.value
    }

    const fn new(name: &'static str, value: PropertyValue<'static>) -> Self {
        Self { name, value }
    }
}

/// The properties of a state, sorted by name ([`State::properties`]).
#[derive(Clone)]
enum PropertyIter {
    /// A table state's rows of [`table::STATE_PROPERTIES`].
    Vanilla(std::slice::Iter<'static, u16>),
    /// A custom state's properties from `at` on, in definition order (which is name order).
    Custom {
        block: &'static custom::Block,
        index: u16,
        at: usize,
    },
}

impl ExactSizeIterator for PropertyIter {}

impl Iterator for PropertyIter {
    type Item = Property;

    #[inline]
    fn next(&mut self) -> Option<Property> {
        match self {
            Self::Vanilla(rows) => rows.next().map(|&p| {
                #[expect(
                    clippy::indexing_slicing,
                    reason = "invariant: the generated state properties index the property table"
                )]
                table::PROPERTIES[usize::from(p)]
            }),
            Self::Custom { block, index, at } => {
                let name = block.property_name(*at)?;
                let value = block.property_value(*index, *at)?;
                *at += 1;
                Some(Property { name, value })
            }
        }
    }

    fn size_hint(&self) -> (usize, Option<usize>) {
        let n = match self {
            Self::Vanilla(rows) => rows.len(),
            Self::Custom { block, at, .. } => block.property_count().saturating_sub(*at),
        };
        (n, Some(n))
    }
}

/// The tools a block is broken faster with and may need to drop anything, as a set of bits.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub struct ToolType(u8);

impl ToolType {
    /// No tool.
    pub const NONE: Self = Self(0);
    /// A sword.
    pub const SWORD: Self = Self(1);
    /// A shovel.
    pub const SHOVEL: Self = Self(1 << 1);
    /// A pickaxe.
    pub const PICKAXE: Self = Self(1 << 2);
    /// An axe.
    pub const AXE: Self = Self(1 << 3);
    /// Shears.
    pub const SHEARS: Self = Self(1 << 4);
    /// A hoe.
    pub const HOE: Self = Self(1 << 5);

    /// The set with these bits. Only generated tables call it.
    pub(crate) const fn from_bits(bits: u8) -> Self {
        Self(bits)
    }

    /// The bits, one per tool type.
    pub const fn bits(self) -> u8 {
        self.0
    }

    /// Whether the two sets share a tool.
    pub const fn intersects(self, other: Self) -> bool {
        self.0 & other.0 != 0
    }
}

impl BitOr for ToolType {
    type Output = Self;

    fn bitor(self, other: Self) -> Self {
        Self(self.0 | other.0)
    }
}

/// How hard a block is to break and which tool it needs.
#[derive(Debug, Clone, Copy, PartialEq)]
#[doc(alias = "BlockBreakInfo")]
pub struct BreakInfo {
    hardness: f64,
    blast_resistance: f64,
    tool_type: ToolType,
    harvest_level: u8,
}

impl BreakInfo {
    /// The factor of the break time with a compatible tool.
    const COMPATIBLE_TOOL_MULTIPLIER: f64 = 1.5;
    /// The factor of the break time without a compatible tool.
    const INCOMPATIBLE_TOOL_MULTIPLIER: f64 = 5.0;

    pub(crate) const fn new(
        hardness: f64,
        blast_resistance: f64,
        tool_type: ToolType,
        harvest_level: u8,
    ) -> Self {
        Self {
            hardness,
            blast_resistance,
            tool_type,
            harvest_level,
        }
    }

    /// The resistance to explosions (usually five times the hardness).
    #[doc(alias = "BlockBreakInfo::getBlastResistance")]
    pub const fn blast_resistance(self) -> f64 {
        self.blast_resistance
    }

    /// The seconds the block takes to break with `tool` (the empty stack is a hand).
    ///
    /// It is the hardness, times 1.5 with a compatible tool or 5 without, divided by the tool's
    /// mining efficiency. The efficiency is a tool's base efficiency plus level² + 1 for an
    /// Efficiency enchantment when its tool type fits the block, else 1; a sword's is half again
    /// either way. `None` for a block that cannot be broken and if the efficiency is not
    /// positive. It is the time before the breaker's conditions (on the ground, in water, Haste,
    /// Mining Fatigue). Leaves, bamboo and wool have rules of their own:
    /// [`State::break_time_secs`] has the time of a given block.
    #[doc(alias = "BlockBreakInfo::getBreakTime")]
    pub fn break_time_secs(self, tool: &item::Stack) -> Option<f64> {
        if !self.is_breakable() {
            return None;
        }
        let item = tool.item();
        let tool_type = item.map_or(ToolType::NONE, item::Type::block_tool_type);
        let harvest_level = item.map_or(0, item::Type::block_tool_harvest_level);
        let multiplier = if self.accepts(tool_type, harvest_level) {
            Self::COMPATIBLE_TOOL_MULTIPLIER
        } else {
            Self::INCOMPATIBLE_TOOL_MULTIPLIER
        };
        let sword = item.is_some_and(|i| i.is(item::Class::Sword));
        // The efficiency is 1 for every item that is not a tool, and for a tool on a block of
        // another tool type.
        let mut efficiency = 1.0;
        if let Some(item) = item
            && item.is(item::Class::Tool)
            && self.tool_type.intersects(tool_type)
        {
            // The table holds the efficiency without enchantments, which for a sword already has
            // the factor 1.5 applied below.
            efficiency = item.mining_efficiency();
            if sword {
                efficiency /= 1.5;
            }
            let level = tool
                .enchantment_level(item::Enchantment::Efficiency)
                .unwrap_or(0);
            if level > 0 {
                let level = f64::from(level);
                efficiency += level * level + 1.0;
            }
        }
        if sword {
            efficiency *= 1.5;
        }
        (efficiency > 0.0).then(|| self.hardness * multiplier / efficiency)
    }

    /// Whether the block breaks at once.
    #[doc(alias = "BlockBreakInfo::breaksInstantly")]
    pub fn breaks_instantly(self) -> bool {
        self.hardness == 0.0
    }

    /// The base of the break time; negative for blocks that cannot be broken.
    #[doc(alias = "BlockBreakInfo::getHardness")]
    pub const fn hardness(self) -> f64 {
        self.hardness
    }

    /// The harvest level a tool of the right type needs for the block to drop (0: none).
    #[doc(alias = "BlockBreakInfo::getToolHarvestLevel")]
    pub const fn harvest_level(self) -> u8 {
        self.harvest_level
    }

    /// Whether a player can break the block in any way (its hardness is not negative).
    #[doc(alias = "BlockBreakInfo::isBreakable")]
    pub fn is_breakable(self) -> bool {
        self.hardness >= 0.0
    }

    /// Whether `tool` (the empty stack is a hand) is the proper tool.
    ///
    /// Then the block drops what a compatible tool gets.
    #[doc(alias = "BlockBreakInfo::isToolCompatible")]
    pub fn is_tool_compatible(self, tool: &item::Stack) -> bool {
        let item = tool.item();
        self.accepts(
            item.map_or(ToolType::NONE, item::Type::block_tool_type),
            item.map_or(0, item::Type::block_tool_harvest_level),
        )
    }

    /// The tools that break the block faster.
    #[doc(alias = "BlockBreakInfo::getToolType")]
    pub const fn tool_type(self) -> ToolType {
        self.tool_type
    }

    /// Whether a tool of these tool types and this harvest level is the proper tool.
    ///
    /// An empty hand is [`ToolType::NONE`] and 0.
    fn accepts(self, tool_type: ToolType, harvest_level: u8) -> bool {
        if self.hardness < 0.0 {
            return false;
        }
        self.tool_type == ToolType::NONE
            || self.harvest_level == 0
            || (self.tool_type.intersects(tool_type) && harvest_level >= self.harvest_level)
    }
}

/// The support a face of a block gives to blocks that need it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
