    /// A block state of the dumps' JSON (`name`, typed `states`): its name and properties.
    fn json_state(json: &serde_json::Value) -> (&str, Vec<(&str, PropertyValue<'_>)>) {
        let properties = json["states"]
            .as_object()
            .unwrap()
            .iter()
            .map(|(k, typed)| {
                let (kind, v) = typed.as_object().unwrap().iter().next().unwrap();
                let value = match kind.as_str() {
                    "byte" => PropertyValue::Byte(u8::try_from(v.as_u64().unwrap()).unwrap()),
                    "int" => PropertyValue::Int(i32::try_from(v.as_i64().unwrap()).unwrap()),
                    "string" => PropertyValue::String(v.as_str().unwrap()),
                    other => panic!("property type {other}"),
                };
                (k.as_str(), value)
            })
            .collect();
        (json["name"].as_str().unwrap(), properties)
    }

