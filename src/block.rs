//! Block states: every block state of the reference list that Anchor places, breaks and sends.
//!
//! A state has its 1.26.60 network ID and its values: light, type, class and traits, break info,
//! physics, collision boxes, support and item form.
//!
//! The states are the Bedrock forms of the dump's block states, upgraded to the client version:
//! where the client version added a property (fence connections, stair corners), every value of
//! it is a state of its own. A reference state the dump has no type for is a state of kind
//! [`Kind::InfoUpdate`] with the reference list's physics (collision boxes, light dampening,
//! hardness); it has no item form. All data lives in static tables generated by `cargo xtask
//! gen`, so nothing is built at start and a lookup never allocates. A vanilla state from outside
//! that is not in the table but that the dump reads as one of its states (the dump ignores some
//! vanilla properties, such as a pumpkin's facing) reads as that state (`State::read`).
//!
//! Where the dump has several states for one Bedrock state, Anchor's state takes the values of
//! one dump type and the block entity holds the rest (the generator's `SHARED` list): a bed's and a
//! banner's colour and a banner's ominous type, whose item form therefore comes from the block
//! entity ([`ItemForm::BlockEntity`]), and a cauldron's contents (Anchor's cauldron with water is
//! the dump's water cauldron; a potion cauldron differs only in having no entity collision).

/// The block flags of [`Info::flags`], as bits (the generator's `BLOCK_FLAGS` order).
pub(crate) mod flag {
    /// The block is solid.
    pub(crate) const SOLID: u16 = 1;
    /// The block is transparent.
    pub(crate) const TRANSPARENT: u16 = 1 << 1;
    /// The block can be replaced when placing another.
    pub(super) const REPLACEABLE: u16 = 1 << 2;
    /// A liquid's current reaches into the block.
    pub(super) const FLOWABLE: u16 = 1 << 3;
    /// The block has entity collision.
    pub(super) const ENTITY_COLLISION: u16 = 1 << 4;
}
