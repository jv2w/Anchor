    /// back is the same state.
    #[test]
    fn every_reference_state_is_a_table_state_or_an_alias_with_its_network_id() {
        let reference = reference();
        assert_eq!(reference.len(), 23_960);
        let mut table_states = 0;
        for json in &reference {
            let (name, mut properties) = json_state(json);
            properties.sort_by_key(|(key, _)| *key);
            let want = u32::try_from(json["network_id"].as_u64().unwrap()).unwrap();
            assert_eq!(
                network_hash(name, properties.iter().copied()),
                want,
                "{name}"
            );
            assert!(is_vanilla_network_id(want), "{name}");
            if let Some(state) = State::from_network_id(want) {
                assert_eq!(State::find(name, &properties), Some(state), "{name}");
                table_states += 1;
            } else {
                assert_eq!(State::find(name, &properties), None, "{name}");
                assert!(State::read(name, &properties).is_some(), "{name}");
            }
        }
        assert_eq!(table_states, State::all().len());
        assert_eq!(reference.len() - table_states, table::ALIASES.len());
        for s in State::all() {
            let hash = network_hash(s.name(), s.properties().map(|p| (p.name(), p.value())));
            assert_eq!(hash, s.network_id(), "{s:?}");
            let disk = crate::save::state_nbt(s);
            assert_eq!(crate::save::find_state(&disk), Some(s), "{s:?}");
        }
        assert_eq!(network_hash("minecraft:unknown", []), 0xffff_fffe);
    }

    /// Every reference state reads as the dump reads it.
    ///
    /// The dump's `deserialized.json` lists the states the dump does not read as themselves: a
    /// state read as itself is that state of the table, one read as another state is that
    /// state's, and one the dump rejects is the table's own state (fence connections, stair
    /// corners, a state without a dump type).
    #[test]
    fn every_reference_state_reads_as_the_state_the_dump_reads_it_as() {
        let reference = reference();
        let listed: Vec<serde_json::Value> =
            serde_json::from_str(include_str!("../xtask/data/dump/deserialized.json")).unwrap();
        let key = |json: &serde_json::Value| format!("{}{}", json["name"], json["states"]);
        let listed: std::collections::BTreeMap<String, &serde_json::Value> =
            listed.iter().map(|d| (key(d), &d["read_as"])).collect();
        let (mut same, mut other, mut rejected) = (0, 0, 0);
        for r in &reference {
            let (name, properties) = json_state(r);
            let expected = match listed.get(&key(r)) {
                Some(serde_json::Value::Null) => {
                    rejected += 1;
                    State::find(name, &properties).expect("a table state")
                }
                Some(read_as) => {
                    other += 1;
                    let (name, properties) = json_state(read_as);
                    State::find(name, &properties).expect("the state it is read as")
                }
                None => {
                    same += 1;
                    State::find(name, &properties).expect("read as itself")
                }
            };
            assert_eq!(State::read(name, &properties), Some(expected), "{}", key(r));
        }
        assert_eq!((same, other, rejected), (8963, 4884, 10_113));
    }

    /// Every alias reads as its state with its properties in any order.
    ///
    /// Changed inputs (another name, one value changed, one property left out or added) never
    /// panic, and a changed value or an added property gives `None`.
    #[test]
    fn aliases_read_in_any_order_and_changed_inputs_never_panic() {
        let pumpkin = |facing| {
            State::read(
                "minecraft:pumpkin",
                &[(
                    "minecraft:cardinal_direction",
                    PropertyValue::String(facing),
                )],
            )
        };
        let south = pumpkin("south");
        assert!(south.is_some());
        for facing in ["north", "east", "west"] {
            assert_eq!(pumpkin(facing), south, "{facing}");
        }
        assert_eq!(pumpkin("up"), None);
        assert_eq!(
            State::read(
                "minecraft:pumpkins",
                &[(
                    "minecraft:cardinal_direction",
                    PropertyValue::String("east")
                )]
            ),
            None
        );
        for a in &table::ALIASES {
            let name = table::NAMES[usize::from(a.name)];
            let mut properties: Vec<(&str, PropertyValue<'_>)> =
                properties_of(a.first_property, a.property_count)
                    .map(|p| (p.name, p.value))
                    .collect();
            properties.reverse();
            assert_eq!(
                State::read(name, &properties),
                Some(State::from_index(a.state))
            );
            for i in 0..properties.len() {
                let mut changed = properties.clone();
                changed[i].1 = match changed[i].1 {
                    PropertyValue::Byte(b) => PropertyValue::Byte(b.wrapping_add(7)),
                    PropertyValue::Int(v) => PropertyValue::Int(v.wrapping_add(1000)),
                    PropertyValue::String(_) => PropertyValue::String("no_such_value"),
                };
                assert_eq!(State::read(name, &changed), None);
                let mut fewer = properties.clone();
                fewer.remove(i);
                let _ = State::read(name, &fewer);
            }
            let mut more = properties.clone();
            more.push(("no_such_property", PropertyValue::Byte(0)));
            assert_eq!(State::read(name, &more), None);
        }
    }

    /// A reference state the dump has no type for reads as `InfoUpdate` and has no item.
    ///
    /// It is a state of the table that is never replaced, and has the reference list's collision
    /// boxes, light and hardness; any tool breaks it as the right one.
    #[test]
    fn a_state_without_a_dump_type_has_the_reference_physics() {
        let names = [
            "beehive",
            "bubble_column",
            "cherry_sapling",
            "composter",
            "decorated_pot",
            "dispenser",
            "dripstone_block",
            "dropper",
            "frog_spawn",
            "kelp",
            "lodestone",
            "mangrove_propagule",
            "moss_block",
            "moss_carpet",
            "observer",
            "piston",
            "piston_arm_collision",
            "pointed_dripstone",
            "scaffolding",
            "seagrass",
            "sticky_piston",
            "suspicious_gravel",
            "turtle_egg",
        ];
        for name in names {
            let full = format!("minecraft:{name}");
            assert!(table::NAMES.binary_search(&full.as_str()).is_ok(), "{full}");
        }
        let moss = state("minecraft:moss_block", &[]);
        let carpet = state("minecraft:moss_carpet", &[]);
        for s in [moss, carpet] {
            assert_eq!(s.kind(), Kind::InfoUpdate, "{s:?}");
            assert_eq!(s.item(), ItemForm::None, "{s:?}");
            assert!(!s.can_be_replaced(), "{s:?}");
            for tool in [
                ToolType::SWORD,
                ToolType::SHOVEL,
                ToolType::PICKAXE,
                ToolType::AXE,
                ToolType::SHEARS,
                ToolType::HOE,
            ] {
                assert!(s.break_info().tool_type().intersects(tool), "{s:?}");
            }
        }
        assert!(moss.is_solid());
        assert_eq!(moss.light_filter(), 15);
        assert_eq!(moss.break_info().hardness(), 0.1);
        assert_eq!(moss.break_time_secs(&item::Stack::EMPTY), Some(0.1 * 1.5));
        assert_eq!(moss.collision_boxes().len(), 1);
        assert!(!carpet.is_solid());
        assert_eq!(carpet.light_filter(), 0);
        assert_eq!(carpet.collision_boxes()[0].max.y, 0.0625);
        for (s, support) in [(moss, SupportType::Full), (carpet, SupportType::None)] {
            for &face in Face::all() {
                assert_eq!(s.support(face), support, "{s:?} {face:?}");
            }
        }
    }

    /// A state outside the reference list is not read.
    ///
    /// That is a value out of range or of another type, and a name that is no reference block.
    #[test]
    fn states_outside_the_reference_list_are_not_read() {
        let kelp = |age| State::read("minecraft:kelp", &[("kelp_age", age)]);
        assert!(kelp(PropertyValue::Int(3)).is_some());
        assert_eq!(kelp(PropertyValue::Int(99)), None);
        assert_eq!(kelp(PropertyValue::Byte(3)), None);
        assert_eq!(kelp(PropertyValue::String("3")), None);
        assert_eq!(State::read("example:moss_block", &[]), None);
    }
