/// A face of a block.
///
/// The order is down (-y), up (+y), north (-z), south (+z), west (-x), east (+x).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Face {
    /// -y.
    Down,
    /// +y.
    Up,
    /// -z.
    North,
    /// +z.
    South,
    /// -x.
    West,
    /// +x.
    East,
}

impl Face {
    /// The four sideways faces, in the order north, south, west, east.
    ///
    /// With [`BlockPos::step`](crate::world::BlockPos::step), they give a block's neighbours on
    /// its level.
    #[doc(alias = "Block::getHorizontalSides")]
    pub const HORIZONTAL: [Self; 4] = [Self::North, Self::South, Self::West, Self::East];

    /// The face numbered `index` ([`Self::index`]); `None` for any other number.
    pub(crate) fn from_index(index: i32) -> Option<Self> {
        usize::try_from(index)
            .ok()
            .and_then(|i| Self::all().get(i).copied())
    }

    /// Every face, in declaration order.
    ///
    /// With [`BlockPos::step`](crate::world::BlockPos::step), it gives a block's six neighbours.
    #[doc(alias = "Block::getAllSides")]
    pub fn all() -> &'static [Self] {
        &[
            Self::Down,
            Self::Up,
            Self::North,
            Self::South,
            Self::West,
            Self::East,
        ]
    }

    /// The face's number (down 0, up 1, north 2, south 3, west 4, east 5).
    ///
    /// Packets, particles and block entities carry it.
    pub(crate) const fn index(self) -> u8 {
        match self {
            Self::Down => 0,
            Self::Up => 1,
            Self::North => 2,
            Self::South => 3,
            Self::West => 4,
            Self::East => 5,
        }
    }

    /// The step one block this way: (x, y, z).
    pub const fn offset(self) -> (i32, i32, i32) {
        match self {
            Self::Down => (0, -1, 0),
            Self::Up => (0, 1, 0),
            Self::North => (0, 0, -1),
            Self::South => (0, 0, 1),
            Self::West => (-1, 0, 0),
            Self::East => (1, 0, 0),
        }
    }

    /// The face on the other side.
    #[must_use]
    pub const fn opposite(self) -> Self {
        match self {
            Self::Down => Self::Up,
            Self::Up => Self::Down,
            Self::North => Self::South,
            Self::South => Self::North,
            Self::West => Self::East,
            Self::East => Self::West,
        }
    }
}

